import * as XLSX from 'xlsx';
import JSZip from 'jszip';
import { saveAs } from 'file-saver';
import { ClientProject, Photo } from '../types';

/**
 * Export selected photos to Excel (.xlsx) file
 */
export function exportSelectionToExcel(client: ClientProject): void {
  const selectedPhotos = client.photos
    .filter(p => p.selected)
    .sort((a, b) => a.sequenceNumber - b.sequenceNumber);

  const formattedDate = client.selectionSubmittedAt
    ? new Date(client.selectionSubmittedAt).toLocaleString('id-ID')
    : new Date().toLocaleString('id-ID');

  const rows = selectedPhotos.map((photo, index) => ({
    'Nomor': index + 1,
    'Nama File': photo.originalName,
    'Status': photo.stage === 'FINAL' ? 'Final Ready' : photo.stage === 'EDIT_PROCESS' ? 'Editing' : 'Selected for Edit',
    'Tanggal Pemilihan': formattedDate,
    'Keterangan': photo.notes || client.clientNotes || 'Pilihan utama wisuda',
  }));

  // Create worksheet
  const worksheet = XLSX.utils.json_to_sheet(rows);

  // Set column widths
  worksheet['!cols'] = [
    { wch: 8 },  // Nomor
    { wch: 35 }, // Nama File
    { wch: 20 }, // Status
    { wch: 24 }, // Tanggal Pemilihan
    { wch: 45 }, // Keterangan
  ];

  // Create workbook
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Pilihan Foto Wisuda');

  // Add metadata sheet
  const metaRows = [
    { Properti: 'Nama Klien', Nilai: client.name },
    { Properti: 'Kode Klien', Nilai: client.code },
    { Properti: 'Universitas', Nilai: client.university },
    { Properti: 'Fakultas', Nilai: client.faculty },
    { Properti: 'Paket', Nilai: client.packageType },
    { Properti: 'Total Foto Dipilih', Nilai: selectedPhotos.length },
    { Properti: 'Batas Kuota', Nilai: client.quotaMaxSelected },
    { Properti: 'Tanggal Submit', Nilai: formattedDate },
    { Properti: 'Catatan Klien', Nilai: client.clientNotes || '-' },
  ];
  const metaSheet = XLSX.utils.json_to_sheet(metaRows);
  metaSheet['!cols'] = [{ wch: 20 }, { wch: 50 }];
  XLSX.utils.book_append_sheet(workbook, metaSheet, 'Informasi Klien');

  const cleanName = client.name.replace(/[^a-zA-Z0-9]/g, '_');
  const filename = `PILIHAN_FOTO_${client.code}_${cleanName}.xlsx`;

  XLSX.writeFile(workbook, filename);
}

/**
 * Export selected photos to clean text file (.txt) for Lightroom / Capture One batch search
 */
export function exportSelectionToTextList(client: ClientProject): void {
  const selectedPhotos = client.photos
    .filter(p => p.selected)
    .sort((a, b) => a.sequenceNumber - b.sequenceNumber);

  const formattedDate = client.selectionSubmittedAt
    ? new Date(client.selectionSubmittedAt).toLocaleString('id-ID')
    : new Date().toLocaleString('id-ID');

  let content = `=====================================================\n`;
  content += `WISUDA BY TANTHOWI - DAFTAR PILIHAN FOTO EDITING\n`;
  content += `=====================================================\n`;
  content += `Klien       : ${client.name}\n`;
  content += `Kode Klien  : ${client.code}\n`;
  content += `Universitas : ${client.university} - ${client.faculty}\n`;
  content += `Tanggal     : ${formattedDate}\n`;
  content += `Total Foto  : ${selectedPhotos.length} / ${client.quotaMaxSelected}\n`;
  content += `Catatan     : ${client.clientNotes || 'Tidak ada catatan'}\n`;
  content += `=====================================================\n\n`;

  content += `[ DAFTAR NAMA FILE ASLI ]\n`;
  selectedPhotos.forEach((photo, idx) => {
    content += `${String(idx + 1).padStart(2, '0')}. ${photo.originalName}\n`;
  });

  content += `\n[ QUICK FILTER STRING UNTUK LIGHTROOM / CAPTURE ONE ]\n`;
  content += selectedPhotos.map(p => p.originalName.replace(/\.[^/.]+$/, '')).join(', ');
  content += `\n\nGenerated by Wisuda by Tanthowi System`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const cleanName = client.name.replace(/[^a-zA-Z0-9]/g, '_');
  saveAs(blob, `DAFTAR_FOTO_${client.code}_${cleanName}.txt`);
}

/**
 * Download photos as a compressed ZIP file
 */
export async function downloadPhotosAsZip(
  photos: Photo[],
  zipFilename: string,
  onProgress?: (percent: number, currentFile: string) => void
): Promise<void> {
  const zip = new JSZip();
  const folder = zip.folder('FOTO_WISUDA_TANTHOWI');

  for (let i = 0; i < photos.length; i++) {
    const photo = photos[i];
    const url = photo.editedUrl || photo.url;
    if (onProgress) {
      onProgress(Math.round(((i + 1) / photos.length) * 100), photo.originalName);
    }

    try {
      const response = await fetch(url);
      const blob = await response.blob();
      folder?.file(photo.originalName, blob);
    } catch (e) {
      console.warn(`Failed to fetch photo ${photo.originalName} for ZIP`, e);
      // Fallback text stub if network is blocked
      folder?.file(`${photo.originalName}.info.txt`, `Foto URL: ${url}\nNomor: ${photo.sequenceNumber}`);
    }
  }

  const content = await zip.generateAsync({ type: 'blob' }, metadata => {
    if (onProgress) {
      onProgress(metadata.percent, 'Mengompres arsip ZIP...');
    }
  });

  saveAs(content, `${zipFilename}.zip`);
}
